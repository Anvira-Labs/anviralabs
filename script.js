// Add parallax effect to hero section
window.addEventListener('scroll', () => {
    const scrolled = window.pageYOffset;
    const hero = document.querySelector('.hero');
    const gradientOrb = document.querySelector('.gradient-orb');
    
    if (hero && gradientOrb && scrolled < window.innerHeight) {
        gradientOrb.style.transform = `translate(-50%, calc(-50% + ${scrolled * 0.5}px))`;
    }
});

// Animate stats counter
const animateCounter = (element, target, suffix, duration = 2000) => {
    let start = 0;
    const increment = target / (duration / 16);
    const timer = setInterval(() => {
        start += increment;
        if (start >= target) {
            element.textContent = target + suffix;
            clearInterval(timer);
        } else {
            element.textContent = Math.floor(start) + suffix;
        }
    }, 16);
};

// Observe stats and animate when visible
const statsObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            const statNumber = entry.target.querySelector('.stat-number');
            const text = statNumber.textContent;
            const number = parseInt(text.replace(/\D/g, ''));
            const suffix = text.includes('/') ? '/7' : '+';
            
            if (number && !statNumber.dataset.animated) {
                statNumber.dataset.animated = 'true';
                statNumber.textContent = '0' + suffix;
                animateCounter(statNumber, number, suffix, 2000);
            }
        }
    });
}, { threshold: 0.5 });

document.querySelectorAll('.stat-item').forEach(stat => {
    statsObserver.observe(stat);
});

// Add hover effect to service cards
